/* 浏览器 API 判空：node 冒烟测试 / SSR 下不炸（隐私模式 localStorage 也可能抛异常） */
const ls = {
  get(k) { try { return typeof localStorage !== 'undefined' ? localStorage.getItem(k) : null } catch (_) { return null } },
  set(k, v) { try { if (typeof localStorage !== 'undefined') localStorage.setItem(k, v) } catch (_) { /* 忽略 */ } },
}

export const i18n = reactive({
  lang: ls.get('gm_lang') === 'zh' ? 'zh' : 'en',
  t(key, ...args) {
    const L = dict[this.lang]
    let s = (L && L[key]) || dict.en[key] || key
    args.forEach((a) => { s = s.replace('%s', () => String(a)) })
    return s
  },
  set(lang) {
    this.lang = lang === 'zh' ? 'zh' : 'en'
    ls.set('gm_lang', this.lang)
    if (typeof document !== 'undefined') document.documentElement.lang = this.lang === 'zh' ? 'zh-CN' : 'en'
  },
  toggle() {
    this.set(this.lang === 'en' ? 'zh' : 'en')
  },
})

export { dict }

if (typeof document !== 'undefined') document.documentElement.lang = i18n.lang === 'zh' ? 'zh-CN' : 'en'
